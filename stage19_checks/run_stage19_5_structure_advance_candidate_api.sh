set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

# Interface compatibility only. Stage 19.5 must not cd into DECOMP2D_ROOT.
: "${DECOMP2D_ROOT:=${REPO_ROOT}}"

: "${STAGE19_5_ENABLE:=1}"
: "${STAGE19_5_ADVANCE_CANDIDATE_ENABLE:=1}"
: "${STAGE19_5_DIAGNOSTIC_ONLY:=1}"
: "${STAGE19_5_SINGLE_FIBRE_ONLY:=1}"
: "${STAGE19_5_FAIL_CLOSED:=1}"
: "${STAGE19_5_FORCE_CANDIDATE_ONLY:=1}"
: "${STAGE19_5_ADVANCE_CANDIDATE_ONLY:=1}"
: "${STAGE19_5_REQUIRE_STAGE19_4_PASS:=1}"
: "${STAGE19_5_REQUIRE_STAGE19_3_PASS:=1}"
: "${STAGE19_5_REQUIRE_STAGE19_2_PASS:=1}"
: "${STAGE19_5_REQUIRE_STAGE19_1_PASS:=1}"
: "${STAGE19_5_REQUIRE_STAGE19_0_PASS:=1}"
: "${STAGE19_5_REQUIRE_STAGE18_CLOSED:=1}"
: "${STAGE19_5_N_FIBRE:=1}"
: "${STAGE19_5_N_POINT:=64}"
: "${STAGE19_5_COMPONENT_DIM:=3}"
