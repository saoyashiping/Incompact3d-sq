export STAGE19_1_CONTACT_MODEL_ENABLE STAGE19_1_FIBRE_FIBRE_COLLISION_ENABLE STAGE19_1_MULTIFIBRE_PRODUCTION_ENABLE
export STAGE19_1_REQUIRE_STAGE19_0_PASS STAGE19_1_REQUIRE_STAGE18_CLOSED
export STAGE19_1_ZERO_TOL STAGE19_1_AUDIT_TOL STAGE19_1_TEST_CASE

mkdir -p "${REPO_ROOT}/stage19_outputs"
OUTPUT="${REPO_ROOT}/stage19_outputs/fibre_stage19_1_physical_structure_config_gate.dat"

python3 "${SCRIPT_DIR}/assert_stage19_1_physical_structure_config_gate.py" \
  --repo-root "${REPO_ROOT}" \
