: "${STAGE19_4_COMMIT_ALLOWED:=0}"
: "${STAGE19_4_RHS_SPREADING_ALLOWED:=0}"
: "${STAGE19_4_STAGE14_RHS_INJECTION_ALLOWED:=0}"
: "${STAGE19_4_ZERO_TOL:=1.0e-14}"
: "${STAGE19_4_AUDIT_TOL:=1.0e-12}"
: "${STAGE19_4_TEST_CASE:=production_bending_tension_force_candidate_api}"

export STAGE19_4_ENABLE STAGE19_4_FORCE_CANDIDATE_ENABLE
export STAGE19_4_DIAGNOSTIC_ONLY STAGE19_4_SINGLE_FIBRE_ONLY STAGE19_4_FAIL_CLOSED STAGE19_4_FORCE_CANDIDATE_ONLY
export STAGE19_4_REQUIRE_STAGE19_3_PASS STAGE19_4_REQUIRE_STAGE19_2_PASS STAGE19_4_REQUIRE_STAGE19_1_PASS STAGE19_4_REQUIRE_STAGE19_0_PASS STAGE19_4_REQUIRE_STAGE18_CLOSED
export STAGE19_4_N_FIBRE STAGE19_4_N_POINT STAGE19_4_COMPONENT_DIM STAGE19_4_FIBRE_LENGTH
