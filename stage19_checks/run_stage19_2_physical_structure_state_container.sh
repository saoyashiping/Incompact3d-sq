#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

# Interface compatibility only. Stage 19.2 must not cd into DECOMP2D_ROOT.
: "${DECOMP2D_ROOT:=${REPO_ROOT}}"

: "${STAGE19_2_ENABLE:=1}"
: "${STAGE19_2_STATE_CONTAINER_ENABLE:=1}"
: "${STAGE19_2_DIAGNOSTIC_ONLY:=1}"
: "${STAGE19_2_SINGLE_FIBRE_ONLY:=1}"
: "${STAGE19_2_FAIL_CLOSED:=1}"
: "${STAGE19_2_REQUIRE_STAGE19_1_PASS:=1}"
: "${STAGE19_2_REQUIRE_STAGE19_0_PASS:=1}"
: "${STAGE19_2_REQUIRE_STAGE18_CLOSED:=1}"
: "${STAGE19_2_N_FIBRE:=1}"
: "${STAGE19_2_N_POINT:=64}"
: "${STAGE19_2_COMPONENT_DIM:=3}"
: "${STAGE19_2_FIBRE_LENGTH:=1.0}"
: "${STAGE19_2_RHO_L:=1.0}"
: "${STAGE19_2_RHO_TILDE:=1.0}"
: "${STAGE19_2_BENDING_STIFFNESS:=1.0e-3}"
: "${STAGE19_2_GAMMA:=1.0e-3}"
: "${STAGE19_2_COMMIT_ALLOWED:=0}"
: "${STAGE19_2_RHS_SPREADING_ALLOWED:=0}"
: "${STAGE19_2_STAGE14_RHS_INJECTION_ALLOWED:=0}"
: "${STAGE19_2_STATE_VALID:=0}"
: "${STAGE19_2_CONTAINER_INITIALIZED:=0}"
: "${STAGE19_2_ZERO_TOL:=1.0e-14}"
: "${STAGE19_2_AUDIT_TOL:=1.0e-12}"
: "${STAGE19_2_TEST_CASE:=production_physical_structure_state_container}"

export STAGE19_2_ENABLE STAGE19_2_STATE_CONTAINER_ENABLE
export STAGE19_2_DIAGNOSTIC_ONLY STAGE19_2_SINGLE_FIBRE_ONLY STAGE19_2_FAIL_CLOSED
export STAGE19_2_REQUIRE_STAGE19_1_PASS STAGE19_2_REQUIRE_STAGE19_0_PASS STAGE19_2_REQUIRE_STAGE18_CLOSED
export STAGE19_2_N_FIBRE STAGE19_2_N_POINT STAGE19_2_COMPONENT_DIM STAGE19_2_FIBRE_LENGTH
export STAGE19_2_RHO_L STAGE19_2_RHO_TILDE STAGE19_2_BENDING_STIFFNESS STAGE19_2_GAMMA
export STAGE19_2_COMMIT_ALLOWED STAGE19_2_RHS_SPREADING_ALLOWED STAGE19_2_STAGE14_RHS_INJECTION_ALLOWED
export STAGE19_2_STATE_VALID STAGE19_2_CONTAINER_INITIALIZED
export STAGE19_2_ZERO_TOL STAGE19_2_AUDIT_TOL STAGE19_2_TEST_CASE

mkdir -p "${REPO_ROOT}/stage19_outputs"
OUTPUT="${REPO_ROOT}/stage19_outputs/fibre_stage19_2_physical_structure_state_container.dat"

python3 "${SCRIPT_DIR}/assert_stage19_2_physical_structure_state_container.py" \
  --repo-root "${REPO_ROOT}" \
  --output "${OUTPUT}"
