export STAGE19_1_ENABLE STAGE19_1_CONFIG_GATE_ENABLE
export STAGE19_1_DIAGNOSTIC_ONLY STAGE19_1_SINGLE_FIBRE_ONLY STAGE19_1_FAIL_CLOSED
export STAGE19_1_PHYSICAL_STRUCTURE_ENABLE STAGE19_1_STRUCTURE_STATE_ENABLE STAGE19_1_STRUCTURE_INIT_ENABLE
export STAGE19_1_FORCE_CANDIDATE_ENABLE STAGE19_1_ADVANCE_CANDIDATE_ENABLE STAGE19_1_COMMIT_ENABLE STAGE19_1_HOOK_ENABLE
