: "${STAGE19_5_SINE_AMPLITUDE:=1.0e-3}"
: "${STAGE19_5_SINE_MODE:=1}"
: "${STAGE19_5_TENSION_MODE:=constant}"
: "${STAGE19_5_TENSION_VALUE:=0.0}"
: "${STAGE19_5_CONTROLLED_FORCE_AMPLITUDE:=0.0}"
: "${STAGE19_5_COMMIT_ALLOWED:=0}"
: "${STAGE19_5_RHS_SPREADING_ALLOWED:=0}"
: "${STAGE19_5_STAGE14_RHS_INJECTION_ALLOWED:=0}"
: "${STAGE19_5_ZERO_TOL:=1.0e-14}"
: "${STAGE19_5_AUDIT_TOL:=1.0e-12}"
: "${STAGE19_5_TEST_CASE:=production_structure_advance_candidate_api}"

export STAGE19_5_ENABLE STAGE19_5_ADVANCE_CANDIDATE_ENABLE
export STAGE19_5_DIAGNOSTIC_ONLY STAGE19_5_SINGLE_FIBRE_ONLY STAGE19_5_FAIL_CLOSED STAGE19_5_FORCE_CANDIDATE_ONLY STAGE19_5_ADVANCE_CANDIDATE_ONLY
export STAGE19_5_REQUIRE_STAGE19_4_PASS STAGE19_5_REQUIRE_STAGE19_3_PASS STAGE19_5_REQUIRE_STAGE19_2_PASS STAGE19_5_REQUIRE_STAGE19_1_PASS STAGE19_5_REQUIRE_STAGE19_0_PASS STAGE19_5_REQUIRE_STAGE18_CLOSED
