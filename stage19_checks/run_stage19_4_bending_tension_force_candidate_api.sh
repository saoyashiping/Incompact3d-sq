set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

# Interface compatibility only. Stage 19.4 must not cd into DECOMP2D_ROOT.
: "${DECOMP2D_ROOT:=${REPO_ROOT}}"

: "${STAGE19_4_ENABLE:=1}"
: "${STAGE19_4_FORCE_CANDIDATE_ENABLE:=1}"
: "${STAGE19_4_DIAGNOSTIC_ONLY:=1}"
: "${STAGE19_4_SINGLE_FIBRE_ONLY:=1}"
: "${STAGE19_4_FAIL_CLOSED:=1}"
: "${STAGE19_4_FORCE_CANDIDATE_ONLY:=1}"
: "${STAGE19_4_REQUIRE_STAGE19_3_PASS:=1}"
: "${STAGE19_4_REQUIRE_STAGE19_2_PASS:=1}"
: "${STAGE19_4_REQUIRE_STAGE19_1_PASS:=1}"
: "${STAGE19_4_REQUIRE_STAGE19_0_PASS:=1}"
: "${STAGE19_4_REQUIRE_STAGE18_CLOSED:=1}"
: "${STAGE19_4_N_FIBRE:=1}"
: "${STAGE19_4_N_POINT:=64}"
: "${STAGE19_4_COMPONENT_DIM:=3}"
: "${STAGE19_4_FIBRE_LENGTH:=1.0}"
