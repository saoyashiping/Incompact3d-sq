#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

# Interface compatibility only. Stage 19.3 must not cd into DECOMP2D_ROOT.
: "${DECOMP2D_ROOT:=${REPO_ROOT}}"

: "${STAGE19_3_ENABLE:=1}"
: "${STAGE19_3_INITIALIZATION_ENABLE:=1}"
: "${STAGE19_3_DIAGNOSTIC_ONLY:=1}"
: "${STAGE19_3_SINGLE_FIBRE_ONLY:=1}"
: "${STAGE19_3_FAIL_CLOSED:=1}"
: "${STAGE19_3_REQUIRE_STAGE19_2_PASS:=1}"
: "${STAGE19_3_REQUIRE_STAGE19_1_PASS:=1}"
: "${STAGE19_3_REQUIRE_STAGE19_0_PASS:=1}"
: "${STAGE19_3_REQUIRE_STAGE18_CLOSED:=1}"
: "${STAGE19_3_N_FIBRE:=1}"
: "${STAGE19_3_N_POINT:=64}"
: "${STAGE19_3_COMPONENT_DIM:=3}"
: "${STAGE19_3_FIBRE_LENGTH:=1.0}"
: "${STAGE19_3_RHO_L:=1.0}"
: "${STAGE19_3_RHO_TILDE:=1.0}"
: "${STAGE19_3_BENDING_STIFFNESS:=1.0e-3}"
: "${STAGE19_3_GAMMA:=1.0e-3}"
: "${STAGE19_3_INIT_MODE:=small_sine_fibre_zero_velocity}"
: "${STAGE19_3_SINE_AMPLITUDE:=1.0e-3}"
: "${STAGE19_3_SINE_MODE:=1}"
: "${STAGE19_3_VELOCITY_AMPLITUDE:=0.0}"
: "${STAGE19_3_CONTROLLED_FORCE_AMPLITUDE:=0.0}"
: "${STAGE19_3_COMMIT_ALLOWED:=0}"
: "${STAGE19_3_RHS_SPREADING_ALLOWED:=0}"
: "${STAGE19_3_STAGE14_RHS_INJECTION_ALLOWED:=0}"
: "${STAGE19_3_STATE_VALID_AFTER_INIT:=1}"
: "${STAGE19_3_CONTAINER_INITIALIZED_AFTER_INIT:=1}"
: "${STAGE19_3_ZERO_TOL:=1.0e-14}"
: "${STAGE19_3_AUDIT_TOL:=1.0e-12}"
: "${STAGE19_3_TEST_CASE:=production_physical_structure_initialization}"

export STAGE19_3_ENABLE STAGE19_3_INITIALIZATION_ENABLE
export STAGE19_3_DIAGNOSTIC_ONLY STAGE19_3_SINGLE_FIBRE_ONLY STAGE19_3_FAIL_CLOSED
export STAGE19_3_REQUIRE_STAGE19_2_PASS STAGE19_3_REQUIRE_STAGE19_1_PASS STAGE19_3_REQUIRE_STAGE19_0_PASS STAGE19_3_REQUIRE_STAGE18_CLOSED
export STAGE19_3_N_FIBRE STAGE19_3_N_POINT STAGE19_3_COMPONENT_DIM STAGE19_3_FIBRE_LENGTH
export STAGE19_3_RHO_L STAGE19_3_RHO_TILDE STAGE19_3_BENDING_STIFFNESS STAGE19_3_GAMMA
export STAGE19_3_INIT_MODE STAGE19_3_SINE_AMPLITUDE STAGE19_3_SINE_MODE STAGE19_3_VELOCITY_AMPLITUDE STAGE19_3_CONTROLLED_FORCE_AMPLITUDE
export STAGE19_3_COMMIT_ALLOWED STAGE19_3_RHS_SPREADING_ALLOWED STAGE19_3_STAGE14_RHS_INJECTION_ALLOWED
export STAGE19_3_STATE_VALID_AFTER_INIT STAGE19_3_CONTAINER_INITIALIZED_AFTER_INIT
export STAGE19_3_ZERO_TOL STAGE19_3_AUDIT_TOL STAGE19_3_TEST_CASE

mkdir -p "${REPO_ROOT}/stage19_outputs"
OUTPUT="${REPO_ROOT}/stage19_outputs/fibre_stage19_3_physical_structure_initialization.dat"

python3 "${SCRIPT_DIR}/assert_stage19_3_physical_structure_initialization.py" \
  --repo-root "${REPO_ROOT}" \
  --output "${OUTPUT}"
