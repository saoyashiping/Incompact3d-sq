export STAGE19_4_INIT_MODE STAGE19_4_SINE_AMPLITUDE STAGE19_4_SINE_MODE STAGE19_4_TENSION_MODE STAGE19_4_TENSION_VALUE STAGE19_4_CONTROLLED_FORCE_AMPLITUDE
export STAGE19_4_COMMIT_ALLOWED STAGE19_4_RHS_SPREADING_ALLOWED STAGE19_4_STAGE14_RHS_INJECTION_ALLOWED
export STAGE19_4_ZERO_TOL STAGE19_4_AUDIT_TOL STAGE19_4_TEST_CASE

mkdir -p "${REPO_ROOT}/stage19_outputs"
OUTPUT="${REPO_ROOT}/stage19_outputs/fibre_stage19_4_bending_tension_force_candidate_api.dat"

