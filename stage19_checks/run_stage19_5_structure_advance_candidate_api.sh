export STAGE19_5_RHO_L STAGE19_5_RHO_TILDE STAGE19_5_BENDING_STIFFNESS STAGE19_5_GAMMA
export STAGE19_5_INIT_MODE STAGE19_5_SINE_AMPLITUDE STAGE19_5_SINE_MODE STAGE19_5_TENSION_MODE STAGE19_5_TENSION_VALUE STAGE19_5_CONTROLLED_FORCE_AMPLITUDE
export STAGE19_5_COMMIT_ALLOWED STAGE19_5_RHS_SPREADING_ALLOWED STAGE19_5_STAGE14_RHS_INJECTION_ALLOWED
export STAGE19_5_ZERO_TOL STAGE19_5_AUDIT_TOL STAGE19_5_TEST_CASE

mkdir -p "${REPO_ROOT}/stage19_outputs"
