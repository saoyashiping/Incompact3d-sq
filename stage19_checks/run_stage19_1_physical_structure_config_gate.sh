: "${DECOMP2D_ROOT:=${REPO_ROOT}}"

: "${STAGE19_1_ENABLE:=1}"
: "${STAGE19_1_CONFIG_GATE_ENABLE:=1}"
: "${STAGE19_1_DIAGNOSTIC_ONLY:=1}"
: "${STAGE19_1_SINGLE_FIBRE_ONLY:=1}"
: "${STAGE19_1_FAIL_CLOSED:=1}"
: "${STAGE19_1_PHYSICAL_STRUCTURE_ENABLE:=0}"
: "${STAGE19_1_STRUCTURE_STATE_ENABLE:=0}"
: "${STAGE19_1_STRUCTURE_INIT_ENABLE:=0}"
: "${STAGE19_1_FORCE_CANDIDATE_ENABLE:=0}"
: "${STAGE19_1_ADVANCE_CANDIDATE_ENABLE:=0}"
: "${STAGE19_1_COMMIT_ENABLE:=0}"
: "${STAGE19_1_HOOK_ENABLE:=0}"
: "${STAGE19_1_FLUID_FORCE_INPUT_ENABLE:=0}"
: "${STAGE19_1_RHS_SPREADING_ENABLE:=0}"
